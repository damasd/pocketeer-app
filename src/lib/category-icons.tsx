export const ICON_KEYS = Object.keys(CATEGORY_ICONS);

/** Renders the Lucide icon stored under `name`; unknown names fall back to "…". */
export function CategoryIcon({ name, size = 20, strokeWidth = 2 }: { name: string; size?: number; strokeWidth?: number }) {
  return createElement(CATEGORY_ICONS[name] ?? Ellipsis, { size, strokeWidth, "aria-hidden": true });
}
